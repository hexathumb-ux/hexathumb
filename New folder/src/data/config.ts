/**
 * Helper to generate a reliable direct WhatsApp URL
 * Normalizes 10-digit Indian numbers (7990026523) to international format (917990026523)
 */
export function getWhatsAppUrl(rawNumber?: string, customText?: string): string {
  const digits = (rawNumber || BRAND_CONFIG.defaultWhatsappNumber).replace(/[^0-9]/g, '');
  // If 10 digits without country code, automatically prepend 91 (India)
  const formattedNumber = digits.length === 10 ? `91${digits}` : digits;
  const message = customText || BRAND_CONFIG.whatsappPrefillMessage;
  return `https://wa.me/${formattedNumber}?text=${encodeURIComponent(message)}`;
}

